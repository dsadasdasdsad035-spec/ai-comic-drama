/** 剧本守则：挂在 SCRIPT_SYS 后面（来自 script-to-manga 的场景要素提取） */
export const SCRIPT_RULES = `

【场景要素提取（每场必填，缺一项后面就会拍不出来）】
1. 人物：谁在场、当前情绪、正在做什么 —— 只写动作与表情，不写心理活动。
2. 时空：地点 + 时间 + 天气/光源。这三项直接决定后面镜头的布光，必须写。
3. 节奏类型：对话 / 铺垫 / 冲突 / 追逐 / 揭示 / 高潮，每场标一个。
4. 冲突强度：0-10 的整数。0-3 平静、4-6 对抗、7-10 爆发。
   拆镜时会按强度决定运镜条数（平静 1 条、对抗 2 条、爆发 3 条），所以必须给。
5. 情绪基调：紧张 / 温情 / 悬疑 / 压抑 / 热血，限 1 个。
每场在 scenes 里额外输出 intensity（整数）与 tone（1 个词）。`

/** 角色守则：挂在 CHARACTER_SYS 后面（来自 character-design-sheet 的一致性排序） */
export const CHARACTER_RULES = `

【一致性铁律（按有效性从高到低）】
1. 有参考图（三视图）时以图为准，文字只补图上看不清的部分；没有参考图才全靠文字锚点。
   所以锚点质量决定成片长相 —— 不要指望模型「听懂」氛围，只认具体特征。
2. look_en 必须包含三项可识别特征，缺一不可：
   发型发色 / 服装主色与材质 / 一个标志性配饰（伤疤、义肢、眼罩、耳饰、纹身等）。
3. 禁止写「帅气」「气质独特」「高级感」「很有故事感」这类画不出来的词。
4. 同一角色的 look_en 一旦定稿，跨镜头逐字复用；同义改写会让模型当成另一个人。
5. 角色区分度先看轮廓（身高、发型、服装剪影），再看配色；轮廓撞了换配色也救不回来。
6. 主要角色控制在 5 个以内，超过必然撞脸。`

